    private void InitializeBufferData(Dictionary<int, EnzymeInfo?> buffers)
    {
        _initializedBuffer = true;
        for (var i = 1; i <= 3; i++)
        {
            var target = i switch { 1 => BufferContainer1, 2 => BufferContainer2, 3 => BufferContainer3, _ => null };
            if (target == null)
                continue;

            if (buffers.TryGetValue(i, out var data) && data != null)
            {
                target.AddChild(CreateBufferContainer(data, i));
                EnableBufferBlock(i);
                DisabledSubjectDiskBlock(i);
            }
            else
            {
                target.AddChild(new Label { Text = Loc.GetString("dna-modifier-button-no-buffer") });
            }
        }
    }

