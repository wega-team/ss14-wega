    private void InitilizeUniqueIdentifiers(UniqueIdentifiersData u)
    {
        _initializedUi = true;
        var grid = new GridContainer
        {
            Columns = 2,
            HorizontalExpand = true,
            Margin = new Thickness(0, 0, 0, 10)
        };

        int GetSpriteCount(ProtoId<MarkingPrototype> style)
        {
            if (string.IsNullOrEmpty(style.Id))
                return 1;

            return _prototypeManager.TryIndex(style, out var proto)
                ? Math.Max(1, proto.Sprites.Count)
                : 1;
        }

        string GetStyleDisplayName(ProtoId<MarkingPrototype> style)
        {
            if (string.IsNullOrEmpty(style.Id))
                return Loc.GetString("dna-modifier-style-none");

            var locKey = $"marking-{style.Id}";
            if (Loc.TryGetString(locKey, out var localized) && !string.IsNullOrEmpty(localized))
                return localized;

            if (_prototypeManager.TryIndex(style, out var proto) && !string.IsNullOrEmpty(proto.Name))
            {
                if (Loc.TryGetString(proto.Name, out var protoLoc) && !string.IsNullOrEmpty(protoLoc))
                    return protoLoc;

                return proto.Name;
            }

            return style.Id;
        }

        string GetSexDisplayName(Sex sex) => sex switch
        {
            Sex.Male => Loc.GetString("dna-modifier-sex-male"),
            Sex.Female => Loc.GetString("dna-modifier-sex-female"),
            _ => Loc.GetString("dna-modifier-sex-unsexed")
        };

        void AddColorRow(string labelLocKey, uint[] colors, string blockPrefix, int spriteCount)
        {
            var wrapper = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                Margin = new Thickness(0, 4, 15, 4)
            };

            wrapper.AddChild(new Label
            {
                Text = Loc.GetString(labelLocKey),
                MinWidth = 120,
                VerticalAlignment = VAlignment.Top
            });

            wrapper.AddChild(new Control { MinWidth = 10 });
            var colorsContainer = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical
            };

            for (var layer = 0; layer < spriteCount; layer++)
            {
                var color = layer < colors.Length
                    ? colors[layer]
                    : (colors.Length > 0 ? colors[^1] : 0u);
                var hex = color.ToString("X6");

                var layerBox = new BoxContainer
                {
                    Orientation = BoxContainer.LayoutOrientation.Horizontal,
                    Margin = new Thickness(0, layer > 0 ? 4 : 0, 0, 0)
                };

                if (spriteCount > 1)
                {
                    layerBox.AddChild(new Label
                    {
                        Text = $"[{layer + 1}]",
                        MinWidth = 24,
                        VerticalAlignment = VAlignment.Center
                    });
                }

                for (var i = 0; i < 6; i++)
                {
                    var btn = new ModifyButton($"{blockPrefix}:{layer}", i)
                    {
                        Text = hex[i].ToString(),
                        MinWidth = 26,
                        Margin = new Thickness(1, 0),
                        ToggleMode = true
                    };
                    btn.OnPressed += _ => OnButtonUiPressed(btn);
                    if (_activeButtonUi == null)
                    {
                        btn.Pressed = true;
                        _activeButtonUi = btn;
                    }
                    layerBox.AddChild(btn);
                }

                colorsContainer.AddChild(layerBox);
            }

            wrapper.AddChild(colorsContainer);
            grid.AddChild(wrapper);
        }

