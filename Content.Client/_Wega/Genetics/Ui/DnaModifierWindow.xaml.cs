    private void OnButtonUiPressed(ModifyButton pressedButton)
    {
        if (pressedButton == _activeButtonUi) { pressedButton.Pressed = true; return; }
        if (_activeButtonUi != null) _activeButtonUi.Pressed = false;
        _activeButtonUi = pressedButton;
        pressedButton.Pressed = true;
    }
