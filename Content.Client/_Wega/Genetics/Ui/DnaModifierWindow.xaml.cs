    private void InitilizeStructuralEnzymes(List<EnzymesPrototypeInfo> enzymes)
    {
        _initializedSe = true;
        var grid = new GridContainer
        {
            Columns = 5,
            HorizontalExpand = true,
            Margin = new Thickness(0, 0, 0, 10)
        };

        for (var i = 0; i < enzymes.Count; i++)
        {
            var enzyme = enzymes[i];
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                Margin = new Thickness(4, 4)
            };
            row.AddChild(new Label { Text = enzyme.Order.ToString(), MinWidth = 25, VerticalAlignment = VAlignment.Center });

            var hex = enzyme.HexCode.ToString("X3");
            for (var d = 0; d < 3; d++)
            {
                var btn = new ModifyButton(enzyme.Order.ToString(), d)
                {
                    Text = hex[d].ToString(),
                    MinWidth = 26,
                    Margin = new Thickness(2, 0),
                    ToggleMode = true
                };
                btn.OnPressed += _ => OnButtonSePressed(btn);
                if (_activeButtonSe == null)
                {
                    btn.Pressed = true;
                    _activeButtonSe = btn;
                }
                row.AddChild(btn);
            }
            grid.AddChild(row);
        }

        SeContainer.AddChild(grid);
    }

    private void OnButtonSePressed(ModifyButton pressedButton)
    {
        if (pressedButton == _activeButtonSe) { pressedButton.Pressed = true; return; }
        if (_activeButtonSe != null) _activeButtonSe.Pressed = false;
        _activeButtonSe = pressedButton;
        pressedButton.Pressed = true;
    }
