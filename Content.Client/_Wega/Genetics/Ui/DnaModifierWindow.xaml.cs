    #region Initilize Rejuve
    private void CreateBeakerUI(Control control, ContainerInfo? info)
    {
        control.RemoveAllChildren();
        if (info == null)
        {
            control.AddChild(new Label { Text = Loc.GetString("dna-modifier-no-container-loaded-text") });
            return;
        }

        control.AddChild(new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            Children =
            {
                new Label { Text = $"{info.DisplayName}: " },
                new Label { Text = $"{info.CurrentVolume}/{info.MaxVolume}" }
            }
        });

        var rowCount = 0;
        if (info.Reagents == null)
            return;

        foreach (var reagent in info.Reagents)
        {
            _prototypeManager.TryIndex(reagent.Reagent.Prototype, out ReagentPrototype? proto);
            var name = proto?.LocalizedName ?? Loc.GetString("dna-modifier-unknown-reagent-text");
            var color = proto?.SubstanceColor ?? default(Color);
            control.AddChild(BuildReagentRow(color, rowCount++, name, reagent.Reagent, reagent.Quantity, true));
        }
    }

    private Control BuildReagentRow(Color reagentColor, int rowCount, string name, ReagentId reagent, FixedPoint2 quantity, bool addButtons)
    {
        var rowColor1 = Color.FromHex("#1B1B1E");
        var rowColor2 = Color.FromHex("#202025");
        var currentRowColor = (rowCount % 2 == 1) ? rowColor1 : rowColor2;
        if (reagentColor == default(Color) || !addButtons)
            reagentColor = currentRowColor;

        var btnList = CreateReagentTransferButtons(reagent, addButtons);
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            Children =
            {
                new Label { Text = $"{name}: " },
                new Label { Text = $"{quantity}u" },
                new Control { HorizontalExpand = true },
                new PanelContainer
                {
                    Name = "colorPanel",
                    VerticalExpand = true,
                    MinWidth = 4,
                    PanelOverride = new StyleBoxFlat { BackgroundColor = reagentColor },
                    Margin = new Thickness(0, 1)
                }
            }
        };

        foreach (var b in btnList)
            row.AddChild(b);

        return new PanelContainer { PanelOverride = new StyleBoxFlat(currentRowColor), Children = { row } };
    }

    private List<ReagentButton> CreateReagentTransferButtons(ReagentId reagent, bool add)
    {
        var list = new List<ReagentButton>();
        if (!add) { return list; }

        var configs = new (string text, DnaModifierReagentAmount amount, string style)[]
        {
            ("1", DnaModifierReagentAmount.U1, StyleClass.ButtonOpenBoth),
            ("5", DnaModifierReagentAmount.U5, StyleClass.ButtonOpenBoth),
            ("10", DnaModifierReagentAmount.U10, StyleClass.ButtonOpenBoth),
            ("25", DnaModifierReagentAmount.U25, StyleClass.ButtonOpenBoth),
            ("50", DnaModifierReagentAmount.U50, StyleClass.ButtonOpenBoth),
            ("100", DnaModifierReagentAmount.U100, StyleClass.ButtonOpenBoth),
            ("All", DnaModifierReagentAmount.All, StyleClass.ButtonOpenLeft),
        };

        foreach (var (text, amount, style) in configs)
        {
            var btn = new ReagentButton(text, amount, reagent, style);
            btn.OnPressed += _ => OnReagentButtonRequested?.Invoke(amount, reagent);
            list.Add(btn);
        }
        return list;
    }

    private sealed class ReagentButton : Button
    {
        public DnaModifierReagentAmount Amount { get; set; }
        public ReagentId Id { get; set; }
        public ReagentButton(string text, DnaModifierReagentAmount amount, ReagentId id, string styleClass)
        {
            AddStyleClass(styleClass);
            Text = text;
            Amount = amount;
            Id = id;
        }
    }
