using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared.Blood.Cult;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Wega.BloodCult.Ui;

[GenerateTypedNameReferences]
public sealed partial class SummoningRuneMenu : FancyWindow
{
    public event Action<NetEntity>? OnCultistSelected;

    public SummoningRuneMenu()
    {
        RobustXamlLoader.Load(this);
    }

    public void InitializeButtons(SummoningRuneBoundUserInterfaceState state)
    {
        CultistsContainer.RemoveAllChildren();

        foreach (var (uid, cultist) in state.Cultists)
        {
            AddCultistButton(cultist.Name, uid, cultist.IsDead);
        }
    }

    private void AddCultistButton(string cultistName, NetEntity cultistUid, bool isDead)
    {
        var button = new Button
        {
            Text = cultistName,
            HorizontalAlignment = HAlignment.Center,
            VerticalAlignment = VAlignment.Center,
            MinSize = new Vector2(300, 32),
            MaxSize = new Vector2(300, 32)
        };

        if (isDead)
            button.Label.FontColorOverride = Color.Red;

        button.OnPressed += _ => HandleCultistSelection(cultistUid);

        CultistsContainer.AddChild(button);
    }

    private void HandleCultistSelection(NetEntity cultistUid)
    {
        OnCultistSelected?.Invoke(cultistUid);
        Close();
    }
}
