using Content.Client._Wega.Barks;
using Content.Client.Corvax.TTS;
using Content.Shared.Preferences;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Wega.Lobby.UI;

[GenerateTypedNameReferences]
public sealed partial class VoiceTab : Control
{
    public event Action<string>? OnTtsVoiceSelected;
    public event Action<string>? OnTtsPreviewRequested;
    public event Action<string>? OnBarkVoiceSelected;
    public event Action<string>? OnBarkPreviewRequested;

    private readonly TTSTab _ttsTab;
    private readonly BarksTab _barksTab;

    private bool _ttsVisible = true;
    private bool _barksVisible = true;

    public VoiceTab()
    {
        RobustXamlLoader.Load(this);

        _ttsTab = new TTSTab();
        _barksTab = new BarksTab();

        SubTabs.AddChild(_ttsTab);   // index 0
        SubTabs.AddChild(_barksTab); // index 1

        SubTabs.SetTabTitle(0, Loc.GetString("humanoid-profile-editor-voice-tab-tts"));
        SubTabs.SetTabTitle(1, Loc.GetString("humanoid-profile-editor-voice-tab-barks"));

        _ttsTab.OnVoiceSelected += id => OnTtsVoiceSelected?.Invoke(id);
        _ttsTab.OnPreviewRequested += id => OnTtsPreviewRequested?.Invoke(id);
        _barksTab.OnVoiceSelected += id => OnBarkVoiceSelected?.Invoke(id);
        _barksTab.OnPreviewRequested += id => OnBarkPreviewRequested?.Invoke(id);
    }

    public void SetTtsVisible(bool visible)
    {
        if (_ttsVisible == visible)
            return;

        _ttsVisible = visible;
        TabContainer.SetTabVisible(_ttsTab, visible);
        EnsureCurrentTabVisible();
    }

    public void SetBarksVisible(bool visible)
    {
        if (_barksVisible == visible)
            return;

        _barksVisible = visible;
        TabContainer.SetTabVisible(_barksTab, visible);
        EnsureCurrentTabVisible();
    }

    private void EnsureCurrentTabVisible()
    {
        if (_ttsVisible && !_barksVisible)
            SubTabs.CurrentTab = 0;
        else if (!_ttsVisible && _barksVisible)
            SubTabs.CurrentTab = 1;
    }

    public void UpdateTtsControls(HumanoidCharacterProfile? profile, string voicePrototype)
    {
        if (profile == null)
            return;

        _ttsTab.UpdateControls(profile, voicePrototype);
        _ttsTab.SetSelectedVoice(profile.TTSVoice);
    }

    public void UpdateBarkControls(HumanoidCharacterProfile? profile)
    {
        if (profile == null)
            return;

        _barksTab.UpdateControls(profile);
        _barksTab.SetSelectedVoice(profile.BarkVoice);
    }

    public void SetSelectedTtsVoice(string voiceId) => _ttsTab.SetSelectedVoice(voiceId);
    public void SetSelectedBarkVoice(string barkId) => _barksTab.SetSelectedVoice(barkId);
}
